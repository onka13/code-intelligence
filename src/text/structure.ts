import { CONTAINER_KINDS } from '../packs/symbols.js';
import type { CodeMap, SymbolNode } from '../model.js';

/** project_structure.md: the public declarations of every file, as Markdown. */

function lines(symbol: SymbolNode): string[] {
  const own = `- \`${symbol.signature}\``;
  if (!CONTAINER_KINDS.has(symbol.kind)) return [own];
  const members = (symbol.members ?? []).filter((m) => m.visibility !== 'private' && m.kind !== 'constructor');
  return [own, ...members.map((m) => `  - \`${m.signature}\``)];
}

export function renderStructure(map: CodeMap): string {
  const files = map.files.filter((f) => f.symbols.some((s) => s.exported));
  const sections = files.map((f) => [`## \`${f.path}\``, '', ...f.symbols.filter((s) => s.exported).flatMap(lines)].join('\n'));
  const intro = `${map.summary.files} files scanned, ${files.length} with public declarations. Generated by code-intelligence ${map.generatorVersion}.`;
  return [`# Project structure: ${map.rootName}`, '', intro, '', ...sections.flatMap((s) => [s, ''])].join('\n');
}
